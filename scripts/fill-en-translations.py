zh_keys = set(_j.loads((ROOT / 'lang' / 'zh.json').read_text(encoding='utf-8')).keys())

filled = 0
for k, v in M.items():
    if k in zh_keys:
        en[k] = v
        filled += 1

# keep en.json ordered like zh.json
zh = _j.loads((ROOT / 'lang' / 'zh.json').read_text(encoding='utf-8'))
out = {k: en.get(k, k) for k in zh}
EN_PATH.write_text(_j.dumps(out, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

missing = [k for k in zh if out[k] == k]
print(f'filled {filled}/{len(M)} | zh={len(zh)} | still untranslated={len(missing)}')
for k in missing[:20]:
    print('  ', repr(k[:60]))
