'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { buildPages } = require('../tui/pages');

function makeRuntime() {
  return { client: {}, cfg: { tui: { days: 30 } }, profileName: 'test' };
}

test('user model library renders teams, provider summaries, stars and searchable details', async () => {
  const runtime = makeRuntime();
  const calls = [];
  const api = async (path, options = {}) => {
    calls.push({ path, options });
    if (path === '/api/user/model-library') return { teams: [{ team_id: 2, team_name: 'Team A', providers: [{ provider_id: 'p1', provider_name: 'Provider A', model_count: 4, visible_model_count: 3, hidden_model_count: 1, test_summary: { tested: 2, success: 1, avg_latency_ms: 20 }, tags: [{ id: 5, name: 'Featured' }] }] }], starred_models: [{ team_id: 2, provider: 'p1', model_id: 'star-1', name: 'Starred', alias: 'Starred', provider_name: 'Provider A', test_ok: false, test_error: `HTTP 400\n${'long upstream error '.repeat(100)}` }], available_series: ['S'], total_models: 4 };
    if (path === '/api/user/api-keys') return [{ id: 1, name: 'Main' }];
    if (path === '/api/user/provider-tags') return [{ id: 5, name: 'Featured' }];
    if (path === '/api/user/providers/quota') return { providers: [{ id: 'quota-p1', name: 'Quota Provider', quota: { planName: 'Pro', total: 1000, remaining: 400, periods: [{ key: 'current_period', label: '本周期', percent: 60 }] }, keys: [{ ok: true, label: '主 Key', quota: { total: 1000, remaining: 400, currentPercent: 60 } }], status: 'success', last_valid_at: '2026-11-24T00:00:00Z' }] };
    if (path === '/api/user/providers/quota/refresh') return { providers: [{ name: 'Quota Provider' }] };
    if (path === '/api/user/model-library/order/by-test') return { teams: 1, providers: 2, models: 3 };
    if (path === '/api/user/team/2/provider/p1/models') return { models: [{ model_id: 'm1', name: 'Model One', provider: 'p1', team_id: 2, team_name: 'Team A', provider_name: 'Provider A', input_price_per_1k_tokens: 0.1, output_price_per_1k_tokens: 0.2, test_ok: true, test_latency_ms: 21, is_starred: false, is_hidden: false }], pagination: { page: 1, total: 1, limit: 30, total_pages: 1, has_prev: false, has_next: false } };
    return {};
  };
  const page = buildPages(runtime).find(item => item.id === 'model-library');
  const initial = await page.load(api);
  assert.ok(initial.pageToolbar);
  assert.ok(initial.actions.filter(action => ['搜索模型/供应商', '选择供应商展开模型', '选择 API Key'].includes(action.label)).every(action => action.toolbar === 'page'));
  const reorderAction = initial.actions.find(action => action.label === '排序模式：保存测试结果排序');
  assert.ok(reorderAction);
  await reorderAction.run({ choose: async () => 'test_tps_desc', confirm: async () => false });
  assert.equal(calls.some(call => call.path === '/api/user/model-library/order/by-test'), false, 'cancelled sort confirmation must not write');
  await reorderAction.run({ choose: async () => 'test_tps_desc', confirm: async () => true, notify() {}, refresh: async () => {} });
  const orderRequest = calls.find(call => call.path === '/api/user/model-library/order/by-test');
  assert.deepEqual(orderRequest.options.body, { sort: 'test_tps_desc' });
  assert.ok(initial.sections.some(section => section.title === '模型库概览'));
  const quotaSection = initial.sections.find(section => section.title === '供应商额度');
  assert.ok(quotaSection);
  assert.match(quotaSection.rows[0].detail, /Pro.*当前周期已用 60%/);
  let quotaDetail = '';
  await quotaSection.rows[0].run({ show: async (_title, body) => { quotaDetail = body; } });
  assert.match(quotaDetail, /本周期：已用 60%/);
  assert.match(quotaDetail, /主 Key：已用 60%/);
  await initial.actions.find(action => action.label === '刷新供应商额度').run({ notify() {}, refresh: async () => {} });
  assert.ok(calls.some(call => call.path === '/api/user/providers/quota/refresh' && call.options.method === 'POST'));
  assert.ok(initial.sections.some(section => section.title === '已收藏模型'));
  const starRow = initial.sections.find(section => section.title === '已收藏模型').rows[0];
  assert.ok(starRow.detail.length < 140, 'long upstream errors must not expand the list row');
  assert.ok(!starRow.detail.includes('\n'), 'multiline upstream error must be collapsed into one summary line');
  let starDetails = '';
  await starRow.run({ choose: async () => 'detail', show: async (_title, body) => { starDetails = body; } });
  assert.match(starDetails, /测试失败原因/);
  assert.ok(!starDetails.includes('input_price_per_1k_tokens') && !starDetails.includes('test_error'), 'details should describe values instead of exposing database field names');
  assert.deepEqual(initial.sections[0].cards.map(card => card.label), ['所属团队', '可用模型', '模型系列', '已收藏模型']);
  const providerSection = initial.sections.find(section => section.title === '团队与供应商目录');
  assert.equal(providerSection.cards.length, 1, 'team provider directory uses the responsive card grid');
  assert.equal(providerSection.cards[0].label, 'Provider A');
  assert.match(providerSection.cards[0].detail, /Team A.*测试通过/);
  let showHidden = await initial.actions.find(action => action.label === '显示已隐藏的项目').run({ refresh: async () => {} });
  assert.equal(runtime.libraryShowHidden, true);
  showHidden = await page.load(api);
  const clearHidden = showHidden.actions.find(action => action.label === '清除所有隐藏偏好');
  assert.ok(clearHidden, 'show-hidden mode exposes the complete-clear action');
  await clearHidden.run({ confirm: async () => false });
  assert.equal(calls.some(call => call.path === '/api/user/model-library/hidden' && call.options.method === 'DELETE'), false);
  await clearHidden.run({ confirm: async () => true, notify() {}, refresh: async () => {} });
  const clearCall = calls.find(call => call.path === '/api/user/model-library/hidden' && call.options.method === 'DELETE');
  assert.deepEqual(clearCall.options.query, { scope: 'all' });
  assert.equal(runtime.libraryShowHidden, false);
  await initial.actions.find(action => action.label === '选择供应商展开模型').run({ choose: async () => 0, refresh: async () => {} });
  const expanded = await page.load(api);
  assert.ok(expanded.sections.some(section => section.title.includes('模型目录')));
  runtime.librarySearch = 'model search';
  runtime.librarySeries = 'S';
  runtime.libraryTest = 'pass';
  runtime.librarySort = 'test_tps_desc';
  await page.load(api);
  const modelSearch = calls.filter(call => call.path === '/api/user/team/2/provider/p1/models').at(-1);
  assert.deepEqual(modelSearch.options.query, { page: 1, limit: 30, search: 'model search', include_hidden: '', series: 'S', test: 'pass', sort: 'test_tps_desc' });
  const hiddenToggle = expanded.actions.find(action => action.label === '显示已隐藏的项目');
  await hiddenToggle.run({ refresh: async () => {} });
  assert.equal(runtime.libraryShowHidden, true);
  await page.load(api);
  assert.equal(calls.filter(call => call.path === '/api/user/team/2/provider/p1/models').at(-1).options.query.include_hidden, '1');
  const modelSection = expanded.sections.find(section => section.title.includes('模型目录'));
  assert.deepEqual(modelSection.columns.map(column => column.label), ['模型名称', '供应商', '系列', '计费倍率', '接口测试', 'Key 队列', '操作']);
  const modelRow = modelSection.rows[0];
  assert.equal(modelRow.cells.multiplier, '计费倍率 ×1.00');
  assert.equal(modelRow.cells.input_price, '0.1 人民币/千Token');
  assert.equal(modelRow.cells.output_price, '0.2 人民币/千Token');
  assert.match(modelRow.cells.test, /通过 21毫秒/);
  assert.equal(modelRow.cells.queue, '未加入');
  assert.ok(modelRow.detail.includes('输入 0.1 人民币/千Token'));
  assert.ok(modelRow.detail.includes('输出 0.2 人民币/千Token'));
  assert.ok(modelRow.detail.includes('上游模型 ID：Model One'));
  assert.equal(modelRow.cells.test, '通过 21毫秒');
  const actions = [];
  const liveApi = async (path, options = {}) => { actions.push({ path, options }); if (path === '/api/user/model-library') return { teams: [{ team_id: 2, team_name: 'Team A', providers: [{ provider_id: 'p1', provider_name: 'Provider A', model_count: 1, visible_model_count: 1 }] }], starred_models: [], available_series: [], total_models: 1 }; if (path === '/api/user/api-keys') return [{ id: 8, name: 'Main Key' }]; if (path === '/api/user/provider-tags') return []; if (path === '/api/user/api-keys/8/models') return { queue: [] }; if (path === '/api/user/team/2/provider/p1/models') return { models: [{ model_id: 'm1', name: 'Model One', provider: 'p1', team_id: 2, team_name: 'Team A', is_starred: false, is_hidden: false }], pagination: { page: 1, total: 1, limit: 30, total_pages: 1, has_prev: false, has_next: false } }; return {}; };
  runtime.libraryProvider = { team_id: 2, provider_id: 'p1', provider_name: 'Provider A' };
  const refreshed = await page.load(liveApi);
  const ready = await page.load(liveApi);
  const readyRow = ready.sections.find(section => section.title.includes('模型目录')).rows[0];
  await readyRow.run({ choose: async () => 'star', confirm: async () => false });
  assert.equal(actions.some(call => call.path === '/api/user/model-library/star'), false);
  await readyRow.run({ choose: async () => 'hide', confirm: async () => true, notify() {}, refresh: async () => {} });
  const hide = actions.find(call => call.path === '/api/user/model-library/hidden');
  assert.deepEqual(hide.options.body, { scope: 'model', teamId: 2, providerId: 'p1', modelId: 'm1', hidden: true });
});
