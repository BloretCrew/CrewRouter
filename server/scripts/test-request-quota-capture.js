'use strict';
const assert = require('node:assert/strict');
const { Pool } = require('pg');
process.env.CRW_MASTER_KEY = 'request-quota-test-only';
const capture = require('../utils/request-quota-capture');
const history = require('../utils/provider-quota-history');

async function main() {
  const provider = { id: 'p', name: '测试', quota_mode: 'script', quota_enabled: true, base_url: 'https://example.invalid',
    api_key: 'secret-key-one', api_keys: [{ key: 'secret-key-one' }, { key: 'secret-key-two' }] };
  assert.equal(capture.captureReason({ quota_enabled: false }), 'quota_not_enabled');
  assert.equal(capture.captureReason({ quota_enabled: true }), null);
  assert.equal(capture.bindIdentity(provider, ''), null);
  const identity = capture.bindIdentity(provider, 'secret-key-two');
  assert.equal(capture.resolveCredential(provider, identity.identity).api_key, 'secret-key-two');
  assert.equal(capture.resolveCredential({ ...provider, api_keys: [{ key: 'replacement' }] }, identity.identity), null);
  assert.deepEqual(capture.usageValues({ input_tokens: 0, output_tokens: -1, points: '1.5' }), ['0', null, null, null, null, null, '1.5']);
  assert.notEqual(capture.configIdentity(provider, identity.identity), capture.configIdentity({ ...provider, quota_script: 'changed' }, identity.identity));
  console.log('request quota pure tests passed');
  if (!process.env.QUOTA_TEST_DATABASE_URL) return;
  const url = new URL(process.env.QUOTA_TEST_DATABASE_URL);
  assert(['127.0.0.1', 'localhost'].includes(url.hostname) && url.pathname.startsWith('/crewrouter_quota_test'));
  const admin = new Pool({ connectionString: url.toString() });
  const schema = `request_capture_${process.pid}`;
  await admin.query(`CREATE SCHEMA ${schema}`);
  const db = new Pool({ connectionString: url.toString(), options: `-c search_path=${schema}` });
  const opts = { pool: db, accountThrottleMs: 0 };
  const success = async (p, options) => history.attachQuotaBatch({ ok: true, status: 200, quota: { unit: 'balance', total: 100, used: 10, remaining: 90 } }, p, options);
  try {
    await db.query(`CREATE TABLE providers(id TEXT PRIMARY KEY,name TEXT,quota_mode TEXT,quota_enabled BOOLEAN,base_url TEXT,api_key TEXT,api_keys JSONB,
      quota_script TEXT,quota_last_result JSONB,quota_last_checked_at TIMESTAMPTZ,quota_last_ok BOOLEAN,quota_last_error TEXT)`);
    await history.ensureQuotaHistorySchema(db);
    await capture.ensureRequestQuotaSchema(db);
    await capture.ensureRequestQuotaSchema(db);
    await require('../utils/quota-cycle-analysis').ensureQuotaCycleSchema(db);
    await db.query('INSERT INTO providers(id,name,quota_mode,quota_enabled,base_url,api_key,api_keys) VALUES($1,$2,$3,$4,$5,$6,$7)',
      [provider.id, provider.name, provider.quota_mode, true, provider.base_url, provider.api_key, JSON.stringify(provider.api_keys)]);
    await history.recordQuotaHistory(db, provider, { ok: true, keys: provider.api_keys.map((_, i) => ({ ok: true, quota: { unit: 'balance', total: 100, used: i, remaining: 100 - i } })) });
    const id = await capture.beginAttempt({ user_id: 1 }, provider, 'secret-key-two', opts);
    let attempt = (await db.query('SELECT * FROM request_attempts WHERE id=$1', [id])).rows[0];
    assert.equal(attempt.credential_identity, identity.identity);
    assert.equal((await db.query('SELECT * FROM request_quota_samples WHERE attempt_id=$1', [id])).rows[0].reused, true);
    await capture.endAttempt(id, { status: 'success', total_tokens: 10, usage_quality: 'actual' }, opts);
    await capture.endAttempt(id, { status: 'failed', total_tokens: 20 }, opts);
    assert.equal((await db.query('SELECT status,total_tokens FROM request_attempts WHERE id=$1', [id])).rows[0].status, 'success');
    assert.equal((await db.query('SELECT * FROM quota_capture_jobs WHERE attempt_id=$1', [id])).rowCount, 1);
    let queried = 0;
    await Promise.all([capture.runWorker({ ...opts, queryQuota: async (p, o) => { queried++; assert.equal(p.api_key, 'secret-key-two'); return success(p, o); } }),
      capture.runWorker({ ...opts, queryQuota: success })]);
    assert.equal((await db.query('SELECT status FROM quota_capture_jobs WHERE attempt_id=$1', [id])).rows[0].status, 'success');
    assert.equal((await db.query('SELECT * FROM provider_quota_account_providers WHERE active=TRUE')).rowCount, 2);
    assert.equal((await db.query('SELECT * FROM request_quota_samples WHERE attempt_id=$1', [id])).rowCount, 2);
    const unsupported = await capture.beginAttempt({}, { ...provider, quota_enabled: false }, 'secret-key-one', opts);
    await capture.endAttempt(unsupported, { status: 'cancelled' }, opts);
    assert.equal((await db.query("SELECT * FROM quota_capture_jobs WHERE attempt_id=$1 AND status='unsupported'", [unsupported])).rowCount, 2);
    const failed = await capture.beginAttempt({}, provider, 'secret-key-one', opts);
    await capture.endAttempt(failed, { status: 'timeout' }, opts);
    await capture.runWorker({ ...opts, queryQuota: async (p, o) => history.attachQuotaBatch({ ok: false, status: 429, error: '429 secret-key-one' }, p, o) });
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='terminal'", [failed])).rows[0].status, 'rate_limited');
    await db.query("UPDATE quota_capture_jobs SET available_at=NOW() WHERE status='rate_limited'");
    await capture.runWorker({ ...opts, queryQuota: success });
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='terminal'", [failed])).rows[0].status, 'success');
    const recovery = await capture.beginAttempt({}, provider, 'secret-key-one', opts);
    await capture.endAttempt(recovery, { status: 'failed' }, opts);
    await db.query("UPDATE quota_capture_jobs SET status='running',lease_until=NOW()-INTERVAL '1 second',lease_token=$2 WHERE attempt_id=$1", [recovery, require('node:crypto').randomUUID()]);
    await capture.runWorker({ ...opts, queryQuota: success });
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1", [recovery])).rows[0].status, 'success');
    const dead = await capture.beginAttempt({}, provider, 'secret-key-one', opts);
    await capture.endAttempt(dead, { status: 'failed' }, opts);
    await capture.runWorker({ ...opts, maxTries: 1, queryQuota: async () => { throw new Error('secret-key-two'); } });
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1", [dead])).rows[0].status, 'failed');
    const changed = await capture.beginAttempt({}, provider, 'secret-key-one', opts);
    await capture.endAttempt(changed, { status: 'success' }, opts);
    await db.query("UPDATE providers SET api_keys='[{\"key\":\"new-key\"}]'");
    await capture.runWorker({ ...opts, queryQuota: success });
    assert.equal((await db.query("SELECT error FROM quota_capture_jobs WHERE attempt_id=$1", [changed])).rows[0].error, 'credential_changed');
    const freshProvider = { ...provider, api_key: 'new-key', api_keys: [{ key: 'new-key' }] };
    const fresh = await capture.beginAttempt({}, freshProvider, 'new-key', opts);
    assert.equal((await db.query("SELECT phase FROM quota_capture_jobs WHERE attempt_id=$1", [fresh])).rows[0].phase, 'baseline');
    await capture.endAttempt(fresh, { status: 'success' }, opts);
    await capture.runWorker({ ...opts, queryQuota: success });
    await db.query("UPDATE quota_capture_jobs SET available_at=NOW() WHERE status='pending'");
    await capture.runWorker({ ...opts, queryQuota: success });
    assert.equal((await db.query("SELECT * FROM request_quota_samples WHERE attempt_id=$1", [fresh])).rowCount, 2);
    await db.query('CREATE TABLE settings(key TEXT PRIMARY KEY,value JSONB)');
    await db.query("INSERT INTO settings VALUES('quota.request_capture_config',$1)", [JSON.stringify({ ...capture.DEFAULT_CAPTURE_CONFIG, mode:'strict', max_tries:3, reconciliation_seconds:12 })]);
    assert.equal((await capture.getCaptureConfig(db,{fresh:true})).mode,'strict');
    assert.equal((await capture.getCaptureConfig(db)).max_tries,3);
    let strictQueries = 0;
    const strictOptions = { ...opts, queryQuota: async (p,o) => { strictQueries++; return success(p,o); } };
    const strict = await capture.beginAttempt({}, freshProvider, 'new-key', strictOptions);
    assert.equal(strictQueries,1);
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='baseline'", [strict])).rows[0].status,'success');
    await capture.endAttempt(strict,{status:'success',total_tokens:25},strictOptions);
    assert.equal(strictQueries,2);
    assert.equal((await db.query("SELECT quality->>'post_start_baseline' AS value FROM request_quota_samples WHERE attempt_id=$1 AND phase='baseline'",[strict])).rows[0].value,'false');
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='terminal'", [strict])).rows[0].status,'success');
    await capture.endAttempt(strict,{total_tokens:30},strictOptions);
    assert.equal(strictQueries,2);
    const timed = await capture.beginAttempt({},freshProvider,'new-key',{ ...opts,strictTimeoutMs:80, queryQuota:async () => new Promise(() => {}) });
    assert.equal((await db.query("SELECT error FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='baseline'",[timed])).rows[0].error,'quota_capture_timeout');
    // 模拟超时后网络忽略abort，账户租约保护后续查询直到到期。
    await db.query("UPDATE quota_capture_account_leases SET lease_until=NOW()-INTERVAL '1 second'");
    const strictFailure = await capture.beginAttempt({},freshProvider,'new-key',{ ...opts, queryQuota: async (p,o) => history.attachQuotaBatch({ok:false,status:502},p,o) });
    assert.equal((await db.query("SELECT status FROM quota_capture_jobs WHERE attempt_id=$1",[strictFailure])).rows[0].status,'failed');
    const passive = await capture.beginAttempt({},freshProvider,'new-key',{ ...opts, queryQuota:async(p,o)=>history.attachQuotaBatch({ok:true,quota:{unit:'balance',total:100,used:10,remaining:90,source:'passive'}},p,o) });
    assert.equal((await db.query("SELECT error FROM quota_capture_jobs WHERE attempt_id=$1",[passive])).rows[0].error,'fresh_sample_unavailable');
    await db.query("UPDATE settings SET value=jsonb_set(value,'{enabled}','false')");
    assert.equal((await capture.getCaptureConfig(db)).enabled,true);
    capture.invalidateCaptureConfig(db);
    assert.equal((await capture.getCaptureConfig(db)).enabled,false);
    const off = await capture.beginAttempt({},freshProvider,'new-key',opts);
    await capture.endAttempt(off,{status:'success'},opts);
    assert.equal((await db.query("SELECT * FROM quota_capture_jobs WHERE attempt_id=$1 AND status='unsupported'",[off])).rowCount,2);
    await db.query("UPDATE settings SET value=jsonb_set(jsonb_set(value,'{enabled}','true'),'{mode}','\"async\"')");
    capture.invalidateCaptureConfig(db);
    const dummyBatch = require('node:crypto').randomUUID();
    const dummyObservation = require('node:crypto').randomUUID();
    const freshAccount = (await db.query('SELECT account_id FROM request_attempts WHERE id=$1',[strict])).rows[0].account_id;
    await db.query("INSERT INTO provider_quota_batches VALUES($1,'p',NOW(),'test','success')",[dummyBatch]);
    await db.query("INSERT INTO provider_quota_observations(id,batch_id,provider_id,account_id,provider_name,source,checked_at,observed_at,status) VALUES($1,$2,'p',$3,'test','test',NOW(),NOW(),'success')",[dummyObservation,dummyBatch,freshAccount]);
    const realBaseline = await capture.beginAttempt({},freshProvider,'new-key',opts);
    assert.notEqual((await db.query("SELECT observation_id FROM request_quota_samples WHERE attempt_id=$1",[realBaseline])).rows[0].observation_id,dummyObservation);
    const parallel = await Promise.all([capture.beginAttempt({},freshProvider,'new-key',opts),capture.beginAttempt({},freshProvider,'new-key',opts)]);
    await Promise.all(parallel.map(id=>capture.endAttempt(id,{status:'success'},opts)));
    let activeQueries=0, maxActive=0;
    const serialQuery = async(p,o)=> { activeQueries++; maxActive=Math.max(maxActive,activeQueries); await new Promise(resolve=>setTimeout(resolve,30)); activeQueries--; return success(p,o); };
    await Promise.all([capture.runWorker({...opts,queryQuota:serialQuery}),capture.runWorker({...opts,queryQuota:serialQuery})]);
    assert.equal(maxActive,1);
    await db.query("UPDATE quota_capture_jobs SET available_at=NOW() WHERE status='pending'");
    await capture.runWorker({...opts,queryQuota:success});
    assert.equal((await db.query("SELECT COUNT(*)::int AS n FROM quota_capture_jobs WHERE attempt_id=ANY($1::uuid[]) AND status='success'",[parallel])).rows[0].n,2);
    const deadOwner = require('node:crypto').randomUUID();
    const liveOwner = require('node:crypto').randomUUID();
    const abandoned = await capture.beginAttempt({started_at:new Date(Date.now()-3600000)},freshProvider,'new-key',{...opts,instanceId:deadOwner,liveLeaseSeconds:1});
    const longStream = await capture.beginAttempt({started_at:new Date(Date.now()-86400000)},freshProvider,'new-key',{...opts,instanceId:liveOwner,liveLeaseSeconds:1});
    await db.query("UPDATE quota_capture_instances SET expires_at=NOW()-INTERVAL '1 second' WHERE id=$1",[deadOwner]);
    await capture.heartbeatInstance(db,{instanceId:liveOwner,liveLeaseSeconds:60});
    const recoveryResults = await Promise.all([capture.recoverInterruptedAttempts(db),capture.recoverInterruptedAttempts(db)]);
    assert(recoveryResults.reduce((n,r)=>n+r.recovered,0)>=1);
    const interrupted=(await db.query('SELECT * FROM request_attempts WHERE id=$1',[abandoned])).rows[0];
    assert.equal(interrupted.status,'failed');
    assert.equal(interrupted.error_class,'process_interrupted');
    assert.equal(interrupted.usage_quality,'unknown');
    assert.equal(interrupted.termination_quality.end_time_basis,'last_owner_heartbeat');
    assert.equal((await db.query('SELECT status FROM request_attempts WHERE id=$1',[longStream])).rows[0].status,'running');
    await capture.recoverInterruptedAttempts(db);
    assert.equal((await db.query("SELECT * FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='terminal'",[abandoned])).rowCount,1);
    const ownerHeartbeat=(await db.query('SELECT heartbeat_at FROM quota_capture_instances WHERE id=$1',[deadOwner])).rows[0].heartbeat_at;
    assert.equal(new Date(interrupted.ended_at).getTime(),new Date(ownerHeartbeat).getTime());
    await capture.endAttempt(longStream,{status:'success'},opts);
    const beatingOwner=require('node:crypto').randomUUID();
    const beating=await capture.beginAttempt({started_at:new Date(Date.now()-86400000)},freshProvider,'new-key',{...opts,instanceId:beatingOwner,liveLeaseSeconds:1});
    capture.startWorker({...opts,instanceId:beatingOwner,liveLeaseSeconds:1,heartbeatIntervalMs:250,queryQuota:success});
    await new Promise(r=>setTimeout(r,1400));
    await capture.recoverInterruptedAttempts(db);
    assert.equal((await db.query('SELECT status FROM request_attempts WHERE id=$1',[beating])).rows[0].status,'running');
    capture.stopWorker();
    await capture.endAttempt(beating,{status:'success'},opts);
    const late = await capture.beginAttempt({},freshProvider,'new-key',{...opts,mode:'strict',strictTimeoutMs:30,queryQuota:async(p,o)=>{await new Promise(r=>setTimeout(r,100));return success(p,o);}});
    await new Promise(r=>setTimeout(r,150));
    assert.equal((await db.query("SELECT error FROM quota_capture_jobs WHERE attempt_id=$1 AND phase='baseline'",[late])).rows[0].error,'quota_capture_timeout');
    const { withQuotaSignal,quotaSignal }=require('../utils/quota-http');
    const aborted=new AbortController();
    await withQuotaSignal(aborted.signal,async()=>{const signal=quotaSignal(AbortSignal.timeout(1000));aborted.abort();assert.equal(signal.aborted,true);});
    const json = JSON.stringify((await db.query('SELECT * FROM request_attempts')).rows) + JSON.stringify((await db.query('SELECT * FROM quota_capture_jobs')).rows);
    assert(!json.includes('secret-key-'));
    await db.query("UPDATE provider_quota_observations SET checked_at=NOW()-INTERVAL '200 days'");
    await history.cleanupQuotaHistory(db, 90);
    assert.equal((await db.query('SELECT * FROM request_quota_samples WHERE observation_id IS NOT NULL')).rowCount, 0);
    assert((await db.query("SELECT * FROM request_quota_samples WHERE jsonb_array_length(COALESCE(normalized_snapshot->'items','[]'))>0")).rowCount >= 2);
    console.log('request quota isolated PG tests passed: exact key, baseline, idempotency, leases, concurrent workers, 429 retry, dead-letter, unsupported, retention');
  } finally {
    await db.end();
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
