'use strict';
const assert = require('assert');
const { normalizeEdition, getCapabilities, metadata, requireTeamEdition } = require('../utils/instance-edition');

assert.strictEqual(normalizeEdition(' personal '), 'personal');
assert.strictEqual(normalizeEdition('TEAM'), 'team');
assert.strictEqual(normalizeEdition('enterprise'), null);
assert.throws(() => getCapabilities(null), /edition/);
const personalCapabilities = getCapabilities('personal');
assert.strictEqual(personalCapabilities.ai, true);
assert.strictEqual(personalCapabilities.modelLibrary, true);
assert.strictEqual(personalCapabilities.models, true);
assert.strictEqual(personalCapabilities.providers, true);
assert.strictEqual(personalCapabilities.playground, true);
assert.strictEqual(personalCapabilities.apiKeys, true);
assert.strictEqual(personalCapabilities.usage, true);
assert.strictEqual(personalCapabilities.multiUser, false);
assert.strictEqual(personalCapabilities.teamAdmin, false);
assert.strictEqual(personalCapabilities.teamMembers, false);
assert.strictEqual(personalCapabilities.sharedApiKeys, false);
assert.strictEqual(personalCapabilities.projects, true);
assert.strictEqual(personalCapabilities.auditLogs, true);
assert.strictEqual(personalCapabilities.teamProjects, false);
assert.strictEqual(personalCapabilities.teamAuditLogs, false);
assert.strictEqual(getCapabilities('team').teamAdmin, true);
assert.strictEqual(getCapabilities('team').models, true);
const local = metadata('personal', { runtime: 'desktop-local', authMode: 'local' });
assert.strictEqual(local.runtime, 'desktop-local');
assert.deepStrictEqual(local.auth, { required: false, methods: ['local'] });
assert.strictEqual(local.capabilities.modelLibrary, true);
assert.deepStrictEqual(metadata('personal').edition, 'personal');

(async () => {
  const guard = requireTeamEdition('personal');
  const response = { statusCode: 200, body: null, status(code) { this.statusCode = code; return this; }, json(body) { this.body = body; } };
  await guard({ session: { user: { id: 1 } } }, response, () => { throw new Error('guard unexpectedly passed'); });
  assert.strictEqual(response.statusCode, 403);
  assert.strictEqual(response.body.type, 'team_edition_required');
  const teamResponse = { statusCode: 200, json() {} };
  let passed = false;
  await requireTeamEdition('team')({}, teamResponse, () => { passed = true; });
  assert.strictEqual(passed, true);
  const setupSource = require('fs').readFileSync(require('path').join(__dirname, '../../public/pages/setup.html'), 'utf8');
  assert.match(setupSource, /data\.existingInstallation \|\| data\.setupComplete/);
  assert.match(setupSource, /stepReady.*style\.display = 'block'/s);
  const fs = require('fs');
  const path = require('path');
  const consolePage = fs.readFileSync(path.join(__dirname, '../../public/pages/console.html'), 'utf8');
  const adminPage = fs.readFileSync(path.join(__dirname, '../../public/pages/admin.html'), 'utf8');
  const appSource = fs.readFileSync(path.join(__dirname, '../../public/js/app.js'), 'utf8');
  const adminSource = fs.readFileSync(path.join(__dirname, '../../public/js/admin.js'), 'utf8');
  assert.match(consolePage, /data-page="modelLibrary"/);
  assert.match(consolePage, /data-page="projectWork" data-capability="projects"/);
  assert.match(consolePage, /data-page="auditLogs" data-capability="auditLogs"/);
  assert.match(adminPage, /data-page="adminUsers" data-capability="multiUser"/);
  assert.match(adminPage, /data-page="adminTeams" data-capability="teamAdmin"/);
  assert.match(adminPage, /data-page="adminUserGroups" data-capability="teamMembers"/);
  assert.match(adminPage, /data-page="adminAuditLogs" data-capability="teamAuditLogs"/);
  assert.match(appSource, /targetPage === 'projectWork' \? 'projects'/);
  assert.match(adminSource, /instance\.capabilities\[el\.dataset\.capability\] === false/);
  const adminRoutes = fs.readFileSync(path.join(__dirname, '../routes/admin.js'), 'utf8');
  assert.match(adminRoutes, /router\.use\(\['\/users', '[^\]]*'\/stats\/multi/);
  const userRoutes = fs.readFileSync(path.join(__dirname, '../routes/user.js'), 'utf8');
  assert.doesNotMatch(userRoutes, /router\.use\([^\n]*'\/project-stats'/);
  assert.match(userRoutes, /router\.get\('\/project-stats', requireAuth/);
  assert.match(userRoutes, /router\.get\('\/audit-logs', requireAuth/);
  assert.match(userRoutes, /getUserPersonalTeam/);
  const serverSource = fs.readFileSync(path.join(__dirname, '../index.js'), 'utf8');
  assert.match(serverSource, /ensureDesktopLocalPersonalTeam/);
  assert.match(serverSource, /ensureDesktopLocalPersonalModels/);
  assert.match(serverSource, /INSERT INTO team_models/);
  assert.match(serverSource, /ON CONFLICT \(team_id, model_id\) DO NOTHING/);
  assert.doesNotMatch(serverSource, /ON CONFLICT \(team_id, model_id\) DO UPDATE SET enabled = TRUE/);
  assert.match(serverSource, /m\.enabled = TRUE AND p\.enabled = TRUE/);
  assert.match(userRoutes, /FROM teams t[\s\S]*t\.is_personal = TRUE/);
  assert.match(userRoutes, /FROM team_models tm[\s\S]*JOIN user_teams ut/);
  assert.match(userRoutes, /JOIN user_teams ut ON ut\.team_id = tm\.team_id AND ut\.user_id = \$1/);
  assert.match(userRoutes, /FROM providers WHERE id = \$1 AND created_by = \$2/);
  assert.doesNotMatch(userRoutes, /WHERE m\.enabled = TRUE AND m\.created_by = \$1/);
  assert.match(userRoutes, /created_by IS NULL OR created_by = \$1/);
  const apiRoutes = fs.readFileSync(path.join(__dirname, '../routes/api.js'), 'utf8');
  assert.match(apiRoutes, /refreshApiUserModelAuthorization/);
  assert.match(apiRoutes, /JOIN user_teams ut ON ut\.team_id = tm\.team_id AND ut\.user_id = \$2/);
  assert.match(apiRoutes, /await refreshApiUserModelAuthorization\(req\.apiUser\)/);
  assert.match(apiRoutes, /modelAuthorization\?\.deniedModelIds\?\.length/);
  assert.match(apiRoutes, /res\.status\(403\)\.json\(\{ error: \{ message: 'One or more API Key model bindings/);
  assert.match(apiRoutes, /const denied = error\?\.code === 'model_access_denied'/);
  const fusionSource = fs.readFileSync(path.join(__dirname, '../fusion/index.js'), 'utf8');
  assert.match(fusionSource, /assertModelAccessForUser/);
  assert.match(fusionSource, /JOIN team_models tm ON tm\.model_id = m\.id AND tm\.enabled = TRUE/);
  assert.match(fusionSource, /JOIN user_teams ut ON ut\.team_id = tm\.team_id AND ut\.user_id = \$2/);
  assert.match(fusionSource, /model_access_denied/);
  const teamRoutes = fs.readFileSync(path.join(__dirname, '../routes/teams.js'), 'utf8');
  assert.match(teamRoutes, /router\.use\(requireTeamEdition/);
  console.log('instance edition validation tests passed');
})().catch((error) => { console.error(error); process.exitCode = 1; });
